const INGREDIENTS = RAW.map((item, index) => ({
  id: 'sys_' + index,
  name: item[0],
  kcal: item[1],
  alias: item[2] || [],
  piece: item[3] || 0
}))

/* 名称 → 食材 的索引，含别名 */
const INDEX = {}
INGREDIENTS.forEach((ing) => {
  INDEX[ing.name] = ing
  ing.alias.forEach((a) => {
    if (!INDEX[a]) INDEX[a] = ing
  })
})

/**
 * 按名称查食材，支持精确、别名、包含匹配
 * @param {string} name
 * @returns {object|null}
 */
function find(name) {
  if (!name) return null
  const key = String(name).trim()
  if (INDEX[key]) return INDEX[key]

  // 去掉常见修饰词再试
  const clean = key
    .replace(/[（(].*?[)）]/g, '')
    .replace(/(适量|少许|新鲜|干的|冷冻|袋装|盒装)/g, '')
    .trim()
  if (clean && INDEX[clean]) return INDEX[clean]

  // 包含匹配：库里名称被输入包含，取最长命中
  let best = null
  INGREDIENTS.forEach((ing) => {
    if (key.indexOf(ing.name) >= 0 && ing.name.length >= 2) {
      if (!best || ing.name.length > best.name.length) best = ing
    }
  })
  if (best) return best

  // 反向：输入被库名称包含
  INGREDIENTS.forEach((ing) => {
    if (ing.name.indexOf(key) >= 0 && key.length >= 2) {
      if (!best || ing.name.length < best.name.length) best = ing
    }
  })
  return best
}

